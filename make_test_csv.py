import os

OUTPUT_DIR = "test_csv"
os.makedirs(OUTPUT_DIR, exist_ok=True)

def write_csv(filename, encoding, rows):
    path = os.path.join(OUTPUT_DIR, filename)
    with open(path, "w", encoding=encoding, newline="") as f:
        f.write("\n".join(rows))
    print(f"  생성: {path}  ({encoding})")


